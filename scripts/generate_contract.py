"""Generate complete JSON wire types from Pydantic; --check rejects schema drift."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend/src"))

from pydantic import TypeAdapter  # noqa: E402
from safer5 import wire  # noqa: E402
from safer5.schemas import Event, LabConfig, LossConfig, RunConfig  # noqa: E402


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "anyOf" in schema:
        return " | ".join(ts(s) for s in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(s, ensure_ascii=False) for s in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    if kind == "object":
        if "properties" in schema:
            return "{\n" + "".join(f"  {json.dumps(name)}: {ts(prop)};\n" for name, prop in schema["properties"].items()) + "}"
        values = schema.get("additionalProperties", {})
        names = schema.get("propertyNames", {})
        return f"Record<{ts(names) if names else 'string'}, {ts(values) if isinstance(values, dict) else 'unknown'}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def main():
    args = argparse.ArgumentParser()
    args.add_argument("--check", action="store_true")
    options = args.parse_args()
    schema = TypeAdapter(Event | LabConfig | LossConfig | RunConfig | wire.Overview | wire.Experiment | wire.Evidence | wire.EventPage | wire.Settings).json_schema()
    content = "// Generated by scripts/generate_contract.py. Do not edit.\n// Complete JSON wire representations; defaults are emitted by the backend.\n\n"
    content += "\n\n".join(f"export type {name} = {ts(value)};" for name,value in sorted(schema["$defs"].items())) + "\n"
    target = ROOT / "frontend/src/generated-contract.ts"
    if options.check:
        if not target.exists() or target.read_text() != content:
            print("Backend/frontend sözleşmesi güncel değil; scripts/generate_contract.py çalıştırın.")
            return 1
    else:
        target.write_text(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
